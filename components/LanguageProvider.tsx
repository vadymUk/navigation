const originalText = new WeakMap<Text, string>();

const languageChangeEvent = "site-language-change";

function getStoredLanguage(): Language {
  const savedLanguage = window.localStorage.getItem("site-language");
  return languages.includes(savedLanguage as Language)
    ? (savedLanguage as Language)
    : "uk";
}

function subscribeToLanguageChange(onStoreChange: () => void) {
  window.addEventListener(languageChangeEvent, onStoreChange);
  return () => window.removeEventListener(languageChangeEvent, onStoreChange);
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const language: Language = useSyncExternalStore(
    subscribeToLanguageChange,
    getStoredLanguage,
    () => "uk",
  );

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    const dictionary = language === "uk" ? undefined : translations[language];
    document
      .querySelectorAll<HTMLInputElement | HTMLTextAreaElement>("[placeholder]")
      .forEach((input) => {
        const source = input.dataset.sourcePlaceholder ?? input.placeholder;
        input.dataset.sourcePlaceholder = source;
        input.placeholder = dictionary?.[source] ?? source;
      });
    const walker = document.createTreeWalker(
      document.body,
      NodeFilter.SHOW_TEXT,
    );
    let node = walker.nextNode() as Text | null;

    while (node) {
      if (!node.parentElement?.closest("script, style, textarea")) {
        const source = originalText.get(node) ?? node.data;
        originalText.set(node, source);
        const trimmedSource = source.trim();
        const translated = dictionary?.[trimmedSource];
        node.data = translated
          ? source.replace(trimmedSource, translated)
          : source;
      }
      node = walker.nextNode() as Text | null;
    }
  }, [language]);

  const changeLanguage = (nextLanguage: Language) => {
    window.localStorage.setItem("site-language", nextLanguage);
    window.dispatchEvent(new Event(languageChangeEvent));
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage: changeLanguage }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
